# Смещения тем относительно общей линии стороны.
OFF = {
    "intern": {"tasks": 0.02, "auto": 0.05, "support": -0.03, "load": -0.06, "feedback": 0.0, "growth": 0.01},
    "mentor": {"tasks": 0.0, "auto": -0.05, "support": 0.03, "load": -0.01, "feedback": 0.02, "growth": 0.0},
}


@dataclass
class SynthPair:
    """Пара с траекториями оценок по месяцам."""

    num: int
    department: str
    intern_line: list[float]
    mentor_line: list[float]
    extra: dict[str, dict[str, float]] = field(default_factory=dict)
    comments: dict[str, dict[int, str]] = field(default_factory=dict)

    @property
    def intern_id(self) -> str:
        return f"С-{100 + self.num}"

    @property
    def mentor_id(self) -> str:
        return f"Н-{200 + self.num}"

    def value(self, side: str, topic: str, month: int) -> float:
        """Оценка стороны по теме в месяце (0-based) на шкале 0–1."""
        base = self.intern_line if side == "intern" else self.mentor_line
        ex = self.extra.get(side, {}).get(topic, 0.0) * (month / 5)
        dip = 0.0
        if topic in ("support", "load") and month in (2, 3):
            dip = -0.15 if month == 2 else -0.08  # системная просадка программы на 3–4-м месяце
        return round(max(0.0, min(1.0, base[month] + OFF[side][topic] + ex + dip)), 3)


